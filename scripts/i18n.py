"""Generate native Android resources and the JVM test/phone projections."""
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
CAT = ROOT / 'i18n/catalog'
GENERATED = ROOT / 'i18n/generated'
SHARED = ROOT / 'core/watch-courier/src/main/kotlin/app/solstone/core/watch/courier/WatchCourierStrings.kt'
HEADER = '// Generated by scripts/i18n.py. Edit i18n/catalog/, then regenerate.\n'

def quote(s):
    return json.dumps(s, ensure_ascii=False).replace('$', r'\$')

def native_text(s):
    # The Android compiler quotes significant whitespace and escapes XML/Android text.
    assert s.startswith('"') and s.endswith('"')
    s = s[1:-1]
    return re.sub(r'\\(u[0-9a-fA-F]{4}|.)', lambda m: chr(int(m[1][1:],16)) if m[1].startswith('u') else {'n':'\n','t':'\t'}.get(m[1],m[1]), s)

def hashes():
    paths = [ROOT / 'i18n/compiler.json', ROOT / 'i18n/messages.json', Path(__file__), ROOT / 'scripts/i18n_preview.py', ROOT / 'scripts/i18n_phone.py', ROOT / 'i18n/native-aliases.json', SHARED]
    paths += [p for base in [CAT,GENERATED,ROOT / 'i18n/previews'] for p in base.rglob('*') if p.is_file() and p.name != 'snapshot.json']
    return {str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(paths)}

def preview_inputs():
    pin=json.loads((ROOT/'i18n/compiler.json').read_text())
    res=GENERATED/'android'/pin['bundle']
    inputs={}
    for folder in sorted(res.glob('values-*')):
        qualifier=folder.name[7:]
        tag=qualifier[2:].replace('+','-') if qualifier.startswith('b+') else qualifier.replace('-r','-')
        table={el.attrib['name']:native_text(el.text or '') for el in ET.parse(folder/'strings.xml').getroot() if el.tag=='string'}
        strings={id:table['m'+id.encode().hex()] for id in ['android.wear.app.name','android.wear.start.a.session','android.wear.open']}
        value={'strings':strings,'tile_source_sha256':hashlib.sha256((ROOT/'apps/wear/src/main/kotlin/app/solstone/observer/wear/WatchTileService.kt').read_bytes()).hexdigest()}
        inputs[tag]={'qualifier':qualifier,'strings':strings,'sha256':hashlib.sha256(json.dumps(value,sort_keys=True,ensure_ascii=False).encode()).hexdigest()}
    return inputs

def check_previews():
    expected=preview_inputs()
    receipt=ROOT/'i18n/previews/manifest.json'
    if not receipt.exists(): sys.exit('Generate catalog-backed tile previews with scripts/i18n_preview.py; see i18n/README.md.')
    actual=json.loads(receipt.read_text())
    if actual['inputs'] != {tag:data['sha256'] for tag,data in expected.items()}:
        sys.exit('Tile preview inputs changed. Build the Wear debug APK and run scripts/i18n_preview.py; see i18n/README.md.')
    images=actual['images']
    paths={f'res/drawable-{data["qualifier"]}-nodpi/wear_tile_preview.png' for data in expected.values()}
    paths.add('res/drawable-nodpi/wear_tile_preview.png')
    if set(images)!=paths: sys.exit('Tile preview locale coverage differs from the catalog.')
    for name,digest in images.items():
        file=receipt.parent/name
        if hashlib.sha256(file.read_bytes()).hexdigest()!=digest: sys.exit('Tile preview bytes changed: '+name)

def main():
    if '--check' in sys.argv:
        check_previews()
        expected=json.loads((GENERATED/'snapshot.json').read_text())
        actual=hashes()
        changed=[p for p in sorted(expected.keys()|actual.keys()) if expected.get(p)!=actual.get(p)]
        if changed:
            sys.exit('Regenerate catalog output with the pinned compiler: '+', '.join(changed))
        print('Catalog source, compiler pin and generated bytes agree.')
        sys.exit(0)

    compiler=os.environ.get('I18N_COMPILER')
    if not compiler: sys.exit('Set I18N_COMPILER to the pinned i18n-catalog executable; see i18n/README.md.')
    pin=json.loads((ROOT/'i18n/compiler.json').read_text())
    subprocess.run([compiler,'targets',str(CAT),'--channel',pin['channel'],'--target','android','--out',str(GENERATED)],check=True,timeout=120)
    from i18n_phone import generate
    generate(ROOT, native_text, quote)
    res=GENERATED/'android'/pin['bundle']
    # English byte equality is part of the migration contract. Other locales retain isolation.
    for folder in ['values','values-en-rUS']:
        p=res/folder/'strings.xml'
        p.write_text(p.read_text().replace('\u2068','').replace('\u2069',''))
    locales=[]
    for folder in sorted(res.glob('values-*')):
        qualifier=folder.name[7:]
        locales.append(qualifier[2:].replace('+','-') if qualifier.startswith('b+') else qualifier.replace('-r','-'))
    (res/'xml').mkdir(exist_ok=True)
    (res/'xml/locales_config.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'+''.join(f'    <locale android:name="{tag}" />\n' for tag in locales)+'</locale-config>\n')
    (GENERATED/'locales.json').write_text(json.dumps(locales,indent=2)+'\n')
    messages=json.loads((ROOT/'i18n/messages.json').read_text())
    xml=ET.parse(res/'values/strings.xml').getroot()
    resources={el.attrib['name']:el for el in xml}
    enum=[]; english=[]
    for id,name in messages.items():
        key='m'+id.encode().hex(); el=resources[key]
        enum.append(f'    {name}(R.{"plurals" if el.tag=="plurals" else "string"}.{key}),')
        if el.tag=='plurals':
            forms={x.attrib['quantity']:native_text(x.text or '') for x in el}
            english.append(f'        WatchMessage.{name} -> if (quantity == 1) {quote(forms["one"])} else {quote(forms["other"])}')
        else: english.append(f'        WatchMessage.{name} -> {quote(native_text(el.text or ""))}')
    (GENERATED/'kotlin').mkdir(); (GENERATED/'test').mkdir()
    (GENERATED/'kotlin/WatchMessage.kt').write_text(HEADER+'package app.solstone.observer.wear\n\ninternal enum class WatchMessage(val resource: Int) {\n'+'\n'.join(enum)+'\n}\n')
    (GENERATED/'test/EnglishWatchCopy.kt').write_text(HEADER+'''package app.solstone.observer.wear

    internal object EnglishWatchCopy : WatchCopy {
        override fun text(message: WatchMessage, vararg arguments: Any): String = render(message, null, arguments)
        override fun quantity(message: WatchMessage, quantity: Int, vararg arguments: Any): String = render(message, quantity, arguments)
        private fun render(message: WatchMessage, quantity: Int?, arguments: Array<out Any>): String {
            val template = when (message) {
    '''+ '\n'.join(english)+'''
            }
            return String.format(java.util.Locale.US, template, *arguments)
        }
    }
    ''')
    test_reader = GENERATED/'test/EnglishWatchCopy.kt'
    test_reader.write_text('\n'.join(line.rstrip() for line in test_reader.read_text().splitlines()).rstrip()+'\n')
    # These three existing shared JVM values remain English until the phone joins the catalog.
    shared={'SOLSTONE':'APP_NAME','RELAY_NOTICE_SHORT':'RELAY_NOTICE_SHORT','RELAY_NOTICE_FULL':'RELAY_NOTICE_FULL'}
    by_name={name:'m'+id.encode().hex() for id,name in messages.items()}
    SHARED.write_text(HEADER+'package app.solstone.core.watch.courier\n\nobject WatchCourierStrings {\n    // Stable source identifier; never localized.\n    const val WATCH = "watch"\n'+''.join(f'    const val {field} = {quote(native_text(resources[by_name[name]].text))}\n' for field,name in shared.items())+'}\n')
    if '--resources-only' in sys.argv:
        print('Native resources generated; preview refresh and snapshot are still required.')
        return
    check_previews()
    (GENERATED/'snapshot.json').write_text(json.dumps(hashes(),indent=2)+'\n')
    print(f'Generated {len(messages)} messages for {locales}.')

if __name__ == "__main__":
    main()
